#!/usr/bin/env node
// Generates docs/TOOLS.md from lib/tools.mjs (wrapper tools) and docs/upstream-tools.json (snapshot of the
// SkyComputerUseClient MCP tool list, decorated the way the wrapper serves it). Run: node scripts/gen-tool-docs.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { EXTRA_TOOLS, decorateUpstreamTools } from "../lib/tools.mjs";
import { VERSION } from "../lib/config.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const upstream = decorateUpstreamTools(JSON.parse(readFileSync(join(root, "docs/upstream-tools.json"), "utf8")));
const prop = (name, p, required) => `| \`${name}\`${required ? " *" : ""} | ${p.type || (p.enum ? "enum" : "")}${p.enum ? ` (${p.enum.join(" \\| ")})` : ""} | ${(p.description || "").replace(/\|/g, "\\|").replace(/\n/g, " ")} |`;
function section(t) {
  const props = t.inputSchema?.properties || {};
  const req = new Set(t.inputSchema?.required || []);
  const rows = Object.entries(props).map(([n, p]) => prop(n, p, req.has(n)));
  const desc = (t.description || "").replace(/\n/g, "\n> ");
  return `### \`${t.name}\`\n\n> ${desc}\n\n${rows.length ? "| Parameter | Type | Description |\n|---|---|---|\n" + rows.join("\n") : "_No parameters._"}\n`;
}
const out = `# Tool reference (codex-cua-plus ${VERSION})

Generated by \`scripts/gen-tool-docs.mjs\` — do not edit by hand. \`*\` = required.

## Upstream tools (Codex Computer Use client, as served by the wrapper)

The wrapper adds \`include_screenshot\`, \`output\`, \`observe\`, \`find\`/\`role\`/\`nth\` and \`press_key.repeat\` to the client's own schemas and normalises key names.

${upstream.map(section).join("\n")}
## Wrapper tools

${EXTRA_TOOLS.map(section).join("\n")}`;
writeFileSync(join(root, "docs/TOOLS.md"), out);
console.log(`docs/TOOLS.md: ${upstream.length} upstream + ${EXTRA_TOOLS.length} wrapper tools`);
